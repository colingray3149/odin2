#[test]
fn write_atomic_final_file_has_requested_mode() {
    let temp = TempRoot::new("write-atomic-mode");
    let root = temp.private_root("private");

    let capability = PrivateCapability::seal(&root).expect("seal private root");
    capability
        .write_atomic(Path::new("report"), b"payload", 0o640)
        .expect("atomic write must succeed");

    let info = capability
        .stat(Path::new("report"))
        .expect("stat final file");
    assert_eq!(
        info.mode & 0o777,
        0o640,
        "the final file must carry the requested mode exactly"
    );
    assert!(info.is_file);

    let mut content = String::new();
    capability
        .open_read(Path::new("report"))
        .expect("reopen final file")
        .read_to_string(&mut content)
        .expect("read final content");
    assert_eq!(content, "payload");

    let error = expect_error(capability.write_atomic(Path::new("report"), b"x", 0o10_000));
    assert!(
        matches!(error, ConfinedError::InvalidMode(0o10_000)),
        "expected InvalidMode for bits outside 0o777, got {error:?}"
    );
    assert_eq!(
        temp.entry_names(&root),
        vec!["report".to_string()],
        "a rejected mode must not touch the directory"
    );
}

#[test]
fn create_exclusive_fails_on_existing_file() {
    let temp = TempRoot::new("create-exclusive");
    let root = temp.private_root("private");

    let capability = PrivateCapability::seal(&root).expect("seal private root");
    {
        let mut first = capability
            .create_exclusive(Path::new("lease"), 0o600)
            .expect("first exclusive create must succeed");
        first.write_all(b"one").expect("write first file");
    }

    let info = capability
        .stat(Path::new("lease"))
        .expect("stat created file");
    assert_eq!(info.mode & 0o777, 0o600);

    let error = expect_error(capability.create_exclusive(Path::new("lease"), 0o600));
    assert!(
        matches!(&error, ConfinedError::AlreadyExists { component } if component == "lease"),
        "expected AlreadyExists on the second exclusive create, got {error:?}"
    );

    let mut content = String::new();
    capability
        .open_read(Path::new("lease"))
        .expect("open surviving file")
        .read_to_string(&mut content)
        .expect("read surviving content");
    assert_eq!(content, "one", "the existing file must not be replaced");
}

#[test]
fn remove_unlinks_the_symlink_without_following_it() {
    let temp = TempRoot::new("remove-no-follow");
    let root = temp.private_root("private");
    temp.write_file("private/target", b"keep", 0o600);
    symlink("target", root.join("link")).expect("symlink sibling target");

    let capability = PrivateCapability::seal(&root).expect("seal private root");
    capability
        .remove(Path::new("link"))
        .expect("removing the symlink entry must succeed");
    capability
        .remove(Path::new("link"))
        .expect("removal is idempotent");

    assert!(
        fs::symlink_metadata(root.join("link")).is_err(),
        "the symlink entry must be gone"
    );
    let info = capability
        .stat(Path::new("target"))
        .expect("the symlink target must survive");
    assert!(info.is_file);
    let mut content = String::new();
    capability
        .open_read(Path::new("target"))
        .expect("open surviving target")
        .read_to_string(&mut content)
        .expect("read surviving target");
    assert_eq!(content, "keep", "removal must not follow the link");
}

#[test]
fn identity_detects_root_inode_swap_after_barrier() {
    let temp = TempRoot::new("root-swap");
    let root = temp.sealed_root("sealed");

    let capability = Capability::seal(&root).expect("seal root");
    let on_disk = fs::metadata(&root).expect("root metadata");
    assert_eq!(
        capability.root_identity(),
        Identity {
            dev: on_disk.dev(),
            ino: on_disk.ino(),
        },
        "root identity must match the named root"
    );
    capability
        .verify_declared_root(&root)
        .expect("the unswapped declared root resolves to the sealed descriptor");

    let error = expect_error(Capability::seal_with_barrier(&root, || {
        fs::rename(&root, temp.child("swapped-away")).expect("move original root aside");
        fs::create_dir(&root).expect("plant replacement directory");
    }));
    match error {
        ConfinedError::RootSwapped { expected, actual } => {
            assert_ne!(
                expected, actual,
                "the planted directory must carry a different identity"
            );
        }
        other => panic!("expected RootSwapped, got {other:?}"),
    }
}

#[test]
fn stat_detects_leaf_inode_swap() {
    let temp = TempRoot::new("leaf-swap");
    let root = temp.sealed_root("sealed");
    temp.write_file("sealed/report", b"original", 0o600);
    temp.write_file("swapped", b"replaced!", 0o600);

    let capability = Capability::seal(&root).expect("seal root");
    let before = capability
        .stat(Path::new("report"))
        .expect("stat before swap");
    assert!(before.is_file && !before.is_dir);
    let on_disk = fs::metadata(root.join("report")).expect("metadata before swap");
    assert_eq!(
        before.identity,
        Identity {
            dev: on_disk.dev(),
            ino: on_disk.ino(),
        },
        "StatInfo identity must match the named file"
    );
    assert_eq!(before.size, 8);

    let error = expect_error(capability.stat_with_leaf_barrier(Path::new("report"), || {
        fs::rename(temp.child("swapped"), root.join("report")).expect("swap leaf inode");
    }));
    assert!(
        matches!(&error, ConfinedError::FinalLeafRace { path } if path == "report"),
        "expected FinalLeafRace after leaf inode swap, got {error:?}"
    );
}

#[test]
fn verify_declared_root_rejects_replacement_after_sealing() {
    let temp = TempRoot::new("declared-root-replacement");
    let root = temp.sealed_root("sealed");
    temp.write_file("sealed/report", b"payload", 0o600);

    let capability = Capability::seal(&root).expect("seal root");
    capability
        .verify_declared_root(&root)
        .expect("the stable declared root must verify");

    fs::rename(&root, temp.child("revoked")).expect("revoke the original root");
    fs::create_dir(&root).expect("plant a replacement root");
    let error = expect_error(capability.verify_declared_root(&root));
    match error {
        ConfinedError::RootSwapped { expected, actual } => {
            assert_ne!(
                expected, actual,
                "the replacement directory must carry a different identity"
            );
        }
        other => panic!("expected RootSwapped, got {other:?}"),
    }

    // A symlink planted at the declared name is equally a typed refusal: the
    // boundary never follows it back to the revoked tree.
    fs::remove_dir(&root).expect("clear the replacement root");
    symlink(temp.child("revoked"), &root).expect("plant a symlinked declared root");
    let error = expect_error(capability.verify_declared_root(&root));
    assert!(
        matches!(&error, ConfinedError::SymlinkEncountered { component } if component == "sealed"),
        "expected SymlinkEncountered for a symlinked declared root, got {error:?}"
    );

    // Restoring the original tree must make the same descriptor usable again.
    fs::remove_file(&root).expect("remove the planted symlink");
    fs::rename(temp.child("revoked"), &root).expect("restore the original root");
    capability
        .verify_declared_root(&root)
        .expect("the restored declared root must verify");
    let info = capability
        .stat(Path::new("report"))
        .expect("read through the restored declared root");
    assert!(info.is_file);
}

#[test]
fn install_exclusive_publishes_once_and_never_replaces() {
    let temp = TempRoot::new("install-exclusive");
    let root = temp.private_root("boundary");
    let capability = PrivateCapability::seal(&root).expect("seal private root");

    capability
        .create_atomic(Path::new(".first.tmp"), b"payload", 0o444)
        .expect("durable staging file");
    capability
        .install_exclusive(Path::new(".first.tmp"), Path::new("models.yml"))
        .expect("the first publication must install");
    capability
        .remove(Path::new(".first.tmp"))
        .expect("retire the consumed staging file");

    {
        let mut installed = capability
            .open_read(Path::new("models.yml"))
            .expect("installed file opens");
        let mut bytes = Vec::new();
        installed
            .read_to_end(&mut bytes)
            .expect("installed bytes read");
        assert_eq!(
            bytes, b"payload",
            "the installed document carries the staged bytes"
        );
    }

    // A second publication against the existing name is the typed
    // no-replace refusal, and the installed document is untouched.
    capability
        .create_atomic(Path::new(".second.tmp"), b"other", 0o444)
        .expect("second staging file");
    let error = expect_error(
        capability.install_exclusive(Path::new(".second.tmp"), Path::new("models.yml")),
    );
    assert!(
        matches!(&error, ConfinedError::AlreadyExists { component } if component == "models.yml"),
        "expected AlreadyExists for the occupied target, got {error:?}"
    );
    capability
        .remove(Path::new(".second.tmp"))
        .expect("retire the refused staging file");
    // Publication requires a regular file and must not follow a symlinked source.
    symlink("models.yml", root.join(".link.tmp")).expect("planted symlink source");
    let error =
        expect_error(capability.install_exclusive(Path::new(".link.tmp"), Path::new("other.yml")));
    assert!(
        matches!(&error, ConfinedError::SymlinkEncountered { component } if component == ".link.tmp"),
        "expected SymlinkEncountered for a symlinked source, got {error:?}"
    );
    {
        let mut installed = capability
            .open_read(Path::new("models.yml"))
            .expect("installed file still opens");
        let mut bytes = Vec::new();
        installed
            .read_to_end(&mut bytes)
            .expect("installed bytes reread");
        assert_eq!(bytes, b"payload", "the occupied document is never replaced");
    }
}

#[test]
fn seal_mount_reads_configmap_generation_links_and_refuses_escapes() {
    let temp = TempRoot::new("mount-read");
    // The kube ConfigMap volume layout: the key is a relative symlink
    // through the `..data` generation symlink into the generation directory.
    let staging = temp.sealed_root("staging");
    let generation = staging.join("..2026_09_24_00_00_00.000000000");
    fs::create_dir(&generation).expect("generation dir");
    temp.write_file(
        "staging/..2026_09_24_00_00_00.000000000/input-1",
        b"{}",
        0o444,
    );
    symlink("..2026_09_24_00_00_00.000000000", staging.join("..data")).expect("generation link");
    symlink("..data/input-1", staging.join("input-1")).expect("key link");

    let capability = Capability::seal_mount(&staging).expect("seal mount root");
    let mut file = capability
        .open_read_beneath(Path::new("input-1"))
        .expect("the generation chain resolves beneath the root");
    let mut bytes = Vec::new();
    file.read_to_end(&mut bytes).expect("staged bytes read");
    assert_eq!(
        bytes, b"{}",
        "the key bytes resolve through the ..data chain"
    );

    // An escape link — absolute or climbing above the root — is refused by
    // the kernel (EPERM/EXDEV/ELOOP) as a typed confinement error.
    symlink("/etc/passwd", staging.join("escape-abs")).expect("absolute escape link");
    let error = expect_error(capability.open_read_beneath(Path::new("escape-abs")));
    assert!(
        matches!(
            error,
            ConfinedError::SymlinkEncountered { .. } | ConfinedError::PermissionDenied { .. }
        ),
        "an absolute escape must refuse typed, got the bytes instead"
    );

    symlink("../../outside", staging.join("escape-rel")).expect("relative escape link");
    let error = expect_error(capability.open_read_beneath(Path::new("escape-rel")));
    assert!(
        matches!(
            error,
            ConfinedError::SymlinkEncountered { .. } | ConfinedError::PermissionDenied { .. }
        ),
        "a climbing escape must refuse typed, got the bytes instead"
    );
}

#[test]
fn ensure_dir_creates_seals_and_refuses_symlink_components() {
    let temp = TempRoot::new("ensure-dir");
    let state = temp.sealed_root("state");

    let agent = PrivateCapability::ensure_dir(&state, Path::new(".omp-agent/run-1"))
        .expect("the agent dir components are created and sealed");
    let created = state.join(".omp-agent").join("run-1");
    let mode = fs::metadata(&created)
        .expect("agent dir metadata")
        .permissions()
        .mode()
        & 0o777;
    assert_eq!(mode, 0o700, "the sealed agent dir is private");
    agent
        .create_atomic(Path::new("probe"), b"inside", 0o444)
        .expect("the sealed authority writes inside its boundary");

    // Re-running over the existing components is an idempotent reseal.
    let resealed = PrivateCapability::ensure_dir(&state, Path::new(".omp-agent/run-1"))
        .expect("existing components reseal");
    resealed
        .open_read(Path::new("probe"))
        .expect("the resealed authority reads the same boundary");

    // A symlinked component refuses instead of being traversed.
    let outside = temp.sealed_root("outside");
    symlink(&outside, state.join("planted")).expect("planted symlink component");
    let error = expect_error(PrivateCapability::ensure_dir(
        &state,
        Path::new("planted/deeper"),
    ));
    assert!(
        matches!(&error, ConfinedError::SymlinkEncountered { component } if component == "planted"),
        "expected SymlinkEncountered for the planted component, got {error:?}"
    );
}

