/// A sealed read-only root and the directories on its way need search
/// permission only (a sops secret generation is `drwxr-x--x root keys`).
#[test]
fn a_search_only_root_seals_and_reads() {
    let scratch = TempRoot::new("search-only");
    let root = scratch.child("outer/root");
    fs::create_dir_all(root.join("inner")).expect("mkdir -p");
    fs::write(root.join("inner/leaf"), b"value").expect("write");
    let modes = |mode: u32| {
        for path in [root.join("inner"), root.clone(), scratch.child("outer")] {
            set_mode(&path, mode);
        }
    };
    modes(0o311);
    let read = Capability::seal(&root)
        .and_then(|capability| capability.open_read(Path::new("inner/leaf")));
    modes(0o755);
    let mut text = String::new();
    read.expect("search permission suffices")
        .read_to_string(&mut text)
        .expect("read");
    assert_eq!(text, "value");
}
