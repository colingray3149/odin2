#[test]
fn open_read_refuses_symlink_that_escapes_the_root() {
    let temp = TempRoot::new("symlink-escape");
    let root = temp.sealed_root("sealed");
    temp.write_file("outside/secret", b"outside", 0o600);
    symlink(temp.child("outside/secret"), root.join("link-file")).expect("symlink file escape");
    symlink(temp.child("outside"), root.join("link-dir")).expect("symlink directory escape");

    let capability = Capability::seal(&root).expect("seal root");

    let error = expect_error(capability.open_read(Path::new("link-file")));
    assert!(
        matches!(&error, ConfinedError::SymlinkEncountered { component } if component == "link-file"),
        "expected SymlinkEncountered for a leaf symlink, got {error:?}"
    );

    let error = expect_error(capability.open_read(Path::new("link-dir/secret")));
    assert!(
        matches!(&error, ConfinedError::SymlinkEncountered { component } if component == "link-dir"),
        "expected SymlinkEncountered for a symlink path component, got {error:?}"
    );

    assert_eq!(
        fs::read(temp.child("outside/secret")).expect("read outside target"),
        b"outside",
        "the escape target must be untouched"
    );
}

