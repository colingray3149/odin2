//! Behavior tests for the confined filesystem boundary.
//!
//! Every failure-path assertion matches a typed [`ConfinedError`] variant,
//! never a rendered string. Fixtures live in a process-unique scratch
//! directory under [`std::env::temp_dir`] and remove themselves on drop; no
//! test reads or writes outside that directory.

use std::fs::{self, Permissions};
use std::io::{Read, Write};
use std::os::unix::fs::{symlink, MetadataExt, PermissionsExt};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

use odin_confined_fs::{
    validate_relative_path, Capability, ConfinedError, GeneratedCapability, Identity,
    PrivateCapability,
};

/// Self-removing scratch directory holding one test's fixture trees.
struct TempRoot {
    path: PathBuf,
}

impl TempRoot {
    fn new(label: &str) -> Self {
        static COUNTER: AtomicU64 = AtomicU64::new(0);
        loop {
            let id = COUNTER.fetch_add(1, Ordering::Relaxed);
            let path = std::env::temp_dir().join(format!(
                "odin-confined-fs-{}-{id}-{label}",
                std::process::id(),
            ));
            match fs::create_dir(&path) {
                Ok(()) => return Self { path },
                Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => continue,
                Err(error) => panic!("create scratch root: {error}"),
            }
        }
    }

    fn child(&self, relative: &str) -> PathBuf {
        self.path.join(relative)
    }

    /// Root directory for [`Capability::seal`].
    fn sealed_root(&self, name: &str) -> PathBuf {
        let root = self.child(name);
        fs::create_dir(&root).expect("create sealed root");
        root
    }

    /// Mode-0700 root required by [`PrivateCapability::seal`].
    fn private_root(&self, name: &str) -> PathBuf {
        let root = self.child(name);
        fs::create_dir(&root).expect("create private root");
        set_mode(&root, 0o700);
        root
    }

    fn write_file(&self, relative: &str, data: &[u8], mode: u32) {
        let path = self.child(relative);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).expect("create fixture parent");
        }
        fs::write(&path, data).expect("write fixture");
        set_mode(&path, mode);
    }

    fn entry_names(&self, dir: &Path) -> Vec<String> {
        let mut names: Vec<String> = fs::read_dir(dir)
            .expect("list directory")
            .map(|entry| {
                entry
                    .expect("read entry")
                    .file_name()
                    .to_string_lossy()
                    .into_owned()
            })
            .collect();
        names.sort();
        names
    }
}

impl Drop for TempRoot {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.path);
    }
}

fn set_mode(path: &Path, mode: u32) {
    fs::set_permissions(path, Permissions::from_mode(mode)).expect("set fixture mode");
}

fn expect_error<T: std::fmt::Debug>(result: Result<T, ConfinedError>) -> ConfinedError {
    result.expect_err("confined operation must fail")
}

#[test]
fn generated_writes_preserve_root_mode_and_confine_linked_entries() {
    let temp = TempRoot::new("generated");
    let root = temp.sealed_root("root");
    set_mode(&root, 0o755);
    assert!(matches!(
        PrivateCapability::seal(&root),
        Err(ConfinedError::PrivateRootNotPrivate { mode: 0o755 })
    ));
    let generated = GeneratedCapability::seal(&root).expect("generated root");
    generated
        .create_dirs(Path::new("pages"), 0o755)
        .expect("pages");
    temp.write_file("outside", b"owner bytes", 0o600);
    symlink(temp.child("outside"), root.join("pages/entry")).expect("linked leaf");
    assert!(matches!(
        generated.open_read(Path::new("pages/entry")),
        Err(ConfinedError::SymlinkEncountered { .. })
    ));
    generated
        .write_atomic(Path::new("pages/entry"), b"generated bytes", 0o600)
        .expect("replace the entry, not its target");
    let mut content = String::new();
    generated
        .open_read(Path::new("pages/entry"))
        .expect("entry")
        .read_to_string(&mut content)
        .expect("read");
    assert_eq!(content, "generated bytes");
    assert_eq!(
        fs::read(temp.child("outside")).expect("outside"),
        b"owner bytes"
    );
    assert_eq!(
        fs::metadata(&root).expect("root mode").mode() & 0o777,
        0o755
    );
    generated.remove(Path::new("pages/entry")).expect("remove");
    assert!(matches!(
        generated.open_read(Path::new("pages/entry")),
        Err(ConfinedError::ComponentMissing { .. })
    ));
    fs::rename(&root, temp.child("moved")).expect("move root");
    fs::create_dir(&root).expect("replacement root");
    assert!(matches!(
        generated.verify_declared_root(&root),
        Err(ConfinedError::RootSwapped { .. })
    ));
    assert_eq!(
        fs::read(temp.child("outside")).expect("outside"),
        b"owner bytes"
    );
}

